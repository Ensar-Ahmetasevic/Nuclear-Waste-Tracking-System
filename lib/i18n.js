// A key may have a singular form "<key>.one", used when `count` is 1.
// "{id:S}" and "{id:P}" print a shipment or Container Profile code (S-000025, P-00202);
// "{actor:U}" prints the person's name from `people`, or "User #id" when unknown.
const CODE_KINDS = { S: "shipment", P: "profile" };
export function translate(locale, key, values, { people } = {}) {
  const lookup = (name) =>
    messages[locale]?.[name] ?? messages[DEFAULT_LOCALE][name];
  const text =
    (values && Number(values.count) === 1 && lookup(`${key}.one`)) ||
    lookup(key) ||
    key;
  return values
    ? text.replace(/\{(\w+)(?::([SPU]))?\}/g, (match, name, code) =>
        values[name] == null
          ? match
          : code === "U"
            ? people?.[values[name]] ?? translate(locale, "common.userNumber", { id: values[name] })
            : code
              ? recordCode(CODE_KINDS[code], values[name])
              : String(values[name]),
      )
    : text;
}
